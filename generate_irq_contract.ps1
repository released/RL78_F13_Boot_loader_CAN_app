param(
    [ValidateSet('Boot','App')][string]$Mode = 'Boot',
    [string]$AppProject = $PSScriptRoot,
    [switch]$CheckOnly
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'app_config.ps1')
$utf8 = New-Object System.Text.UTF8Encoding($false)
$config = (@('image_metadata_config.h','can_boot_config.h','boot_app_handoff.h') |
    ForEach-Object { [IO.File]::ReadAllText((Join-Path $PSScriptRoot $_)) }) -join "`n"
$config = [regex]::Replace($config, '(?s)/\*.*?\*/|//[^\r\n]*', '')
function Macro([string]$name) {
    $definitions = [regex]::Matches($config, '(?m)^#define\s+'+[regex]::Escape($name)+'\s+\((0x[0-9A-Fa-f]+|[0-9]+)[UL]*\)[ \t]*\r?$')
    if ($definitions.Count -ne 1) { throw "Missing or duplicate numeric contract macro $name" }
    $m = $definitions[0]
    return [Convert]::ToUInt32($m.Groups[1].Value.Replace('0x',''), $(if($m.Groups[1].Value.StartsWith('0x')){16}else{10}))
}
function Generated([string]$path,[string]$value) {
    $value = $value.Replace("`r`n","`n").Replace("`n","`r`n")
    if ($CheckOnly) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -cne $value) { throw "Stale generated IRQ contract: $path" }
    } elseif (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -cne $value) {
        [IO.File]::WriteAllText($path,$value,$utf8)
    }
}
$start = Macro 'IMAGE_APPLICATION_START'
if ($start -ne 0x2000) { throw 'This IRQ ABI requires the F13 app table at 0x2000.' }
if ((Macro 'BOOT_APP_RAM_OWNER_OFFSET') -ne 0 -or (Macro 'BOOT_APP_SHARED_RAM_ADDRESS') -ne 0xFF710) {
    throw 'This IRQ ABI requires the owner byte at 0xFF710.'
}
if ($Mode -eq 'Boot') {
    $text = "; Generated by generate_irq_contract.ps1 -Mode Boot. Do not edit.`n"
    $text += "; Complete normal-vector ownership; no dependency on app handler names.`n"
    $text += ".EXTERN _f13_boot_timer_isr`n.SECTION .text, TEXT`n"
    for ($v=4; $v -le 0x7C; $v+=2) {
        $text += ('f13_irq_{0:X2} .VECTOR 0x{0:X2}' -f $v)+"`n"
        $text += ('f13_irq_{0:X2}:' -f $v)+"`n    CALL !f13_irq_dispatch`n"
        $text += ('    .DB 0x{0:X2}' -f $v)+"`n"
    }
    # CALL pushes four bytes. Three PUSH words put its low PC at SP+6.
    # RET consumes only that synthetic CALL frame, never the hardware IRQ frame.
    $text += @'
; Preserve AX/HL/ES, with IE still disabled. BC/DE/CS are untouched.
; The literal is a byte: no unaligned ROM word access is required.
f13_irq_dispatch:
    PUSH AX
    PUSH HL
    MOV A,ES
    PUSH AX
    MOV ES,#0
    MOVW AX,[SP+6]
    MOVW HL,AX
    MOV A,ES:[HL]
    MOV X,A
    MOV A,#0
    SHLW AX,1
'@  # AX is little-endian X(low), A(high).
    $text += "`n"+('    ADDW AX,#0x{0:X4}' -f $start)+"`n"
    $text += ('    CMP !0x{0:X4},#0x{1:X2}' -f ((Macro 'BOOT_APP_SHARED_RAM_ADDRESS') -band 0xFFFF),(Macro 'BOOT_APP_RAM_OWNER_APPLICATION'))+"`n"
    $text += "    BZ `$f13_irq_target`n"
    $text += ('    CMP !0x{0:X4},#0x{1:X2}' -f ((Macro 'BOOT_APP_SHARED_RAM_ADDRESS') -band 0xFFFF),(Macro 'BOOT_APP_RAM_OWNER_BOOT'))+"`n"
    $text += "    BNZ `$f13_irq_default`n"
    $text += ('    CMPW AX,#0x{0:X4}' -f ($start+0x1E*2))+"`n"
    $text += @'
    BNZ $f13_irq_default
    MOVW AX,#LOWW(_f13_boot_timer_isr)
    BR $f13_irq_target
f13_irq_default:
    MOVW AX,#LOWW(f13_boot_default_isr)
f13_irq_target:
    MOVW [SP+6],AX
    POP AX
    MOV ES,A
    POP HL
    POP AX
    RET
f13_boot_default_isr:
    RETI
; Reset remains in cstart. Reserved 0x02 and debugger BRK 0x7E are not routed.
'@
    Generated (Join-Path $PSScriptRoot 'f13_boot_vectors.asm') ($text+"`n")
} else {
    $AppProject = (Resolve-Path -LiteralPath $AppProject).Path
    $image = Read-AppImageConfig $AppProject (Macro 'IMAGE_TARGET_ID')
    $version = $image.Version
    $equ = [ordered]@{
        FLASH_TABLE = $start
        INTERRUPT_OFFSET = (Macro 'IMAGE_MANIFEST_OFFSET')
        APP_MANIFEST_TABLE = ($start + (Macro 'IMAGE_MANIFEST_OFFSET'))
        IMAGE_MANIFEST_MAGIC = (Macro 'IMAGE_MANIFEST_MAGIC')
        IMAGE_MANIFEST_FORMAT_INFO = ((Macro 'IMAGE_FORMAT_VERSION') -bor ((Macro 'IMAGE_MANIFEST_SIZE') -shl 8) -bor ((Macro 'IMAGE_MANIFEST_FLAGS') -shl 16))
        IMAGE_METADATA_REGION_SIZE = (Macro 'IMAGE_METADATA_REGION_SIZE')
        IMAGE_MANIFEST_PROTOCOL = ((Macro 'CAN_BOOT_PROTOCOL_ID') -bor ((Macro 'CAN_BOOT_PROTOCOL_VERSION') -shl 16) -bor ((Macro 'IMAGE_CHECKSUM_CRC32') -shl 24))
        IMAGE_MANIFEST_TARGET = ((Macro 'IMAGE_TARGET_ID') -bor ((Macro 'CAN_BOOT_CAN_MODE_CLASSICAL') -shl 16) -bor ((Macro 'CAN_BOOT_CAN_ID_STANDARD') -shl 24))
        APP_IMAGE_VERSION = $version
        APP_IMAGE_BUILD = [uint32]$image.build
        APP_IMAGE_VERSION_CONTROL = [uint32]$image.VersionControl
        IMAGE_SIZE_POST_BUILD = [uint32]::MaxValue
        APP_REGION_SIZE = (Macro 'IMAGE_APPLICATION_CAPACITY')
        CODE_FLASH_SIZE = (Macro 'IMAGE_CODE_FLASH_SIZE')
        BOOT_RESERVED_SIZE = (Macro 'IMAGE_RESERVED_SIZE')
        FLASH_ERASE_BLOCK_SIZE = (Macro 'IMAGE_ERASE_BLOCK_SIZE')
        CAN_NOMINAL_BITRATE_MASK = (Macro 'CAN_BOOT_NOMINAL_500K_MASK')
        CAN_DATA_BITRATE_MASK = (Macro 'CAN_BOOT_DATA_BITRATE_MASK')
        CAN_REQUEST_ID = (Macro 'CAN_BOOT_REQUEST_ID')
        CAN_RESPONSE_ID = (Macro 'CAN_BOOT_RESPONSE_ID')
        MINIMUM_IMAGE_SIZE = (Macro 'IMAGE_MINIMUM_IMAGE_SIZE')
        IMAGE_POLICY_WORD = (Macro 'IMAGE_POLICY_WORD')
        IMAGE_IRQ_ABI = (Macro 'IMAGE_IRQ_ABI')
        IMAGE_MIN_BOOT_VERSION = (Macro 'IMAGE_BOOT_VERSION')
    }
    foreach ($field in @('PART_0','PART_1','PART_2','PART_3','FAMILY_0','FAMILY_1','FAMILY_2')) {
        $equ['MCU_'+$field] = Macro ('IMAGE_MCU_'+$field)
    }
    $table = "; Generated from this App's app_image_config.h and Boot contract. Do not edit.`n"
    foreach ($field in $equ.Keys) {
        $table += ('{0,-28} .EQU 0x{1:X8}' -f $field,$equ[$field])+"`n"
    }
    $map = Read-AppIrqConfig $AppProject
    $allowed=@{}
    $header=[IO.File]::ReadAllText((Join-Path $AppProject 'iodefine.h'))
    foreach($entry in [regex]::Matches($header,'#define\s+INT\w+\s+(0x[0-9A-Fa-f]+)')) {
        $allowed[[Convert]::ToInt32($entry.Groups[1].Value.Substring(2),16)]=$true
    }
    foreach($v in $map.Keys) {
        if($v -gt 0x62 -or !$allowed.ContainsKey($v)) { throw "Reserved/non-normal F13 vector: $v" }
    }
    $text = "; Generated from this app's app_irq_handlers.h. Do not edit.`n.EXTERN _start`n"
    $projects = @(Get-ChildItem -LiteralPath $AppProject -Filter '*.mtpj')
    if ($projects.Count -ne 1) { throw 'Exactly one app MTPJ is required.' }
    [xml]$project = [IO.File]::ReadAllText($projects[0].FullName)
    $sources = @($project.SelectNodes('//Instance[Type="File"]') | Where-Object { $_.RelativePath -match '\.c$' } | ForEach-Object {
        $path = [string]$_.RelativePath
        if (![IO.Path]::IsPathRooted($path)) { $path = Join-Path $AppProject $path }
        [IO.File]::ReadAllText($path)
    })
    foreach ($symbol in $map.Values) {
        $declarations = @($sources | Where-Object { $_ -match ('(?m)^\s*#pragma\s+interrupt\s+'+[regex]::Escape($symbol)+'\s*\r?$') })
        if ($declarations.Count -ne 1) { throw "Handler $symbol requires one normal interrupt pragma without vect in registered sources." }
    }
    foreach ($symbol in @($map.Values | Sort-Object -Unique)) { $text += ".EXTERN _$symbol`n" }
    $text += ".jtext .CSEG AT FLASH_TABLE`n    BR !!_start ; RESET 0x00`n    .DB4 0xFFFFFFFF ; Reserved 0x02`n"
    for ($v=4; $v -le 0x7C; $v+=2) {
        $symbol = if ($map.ContainsKey($v)) {'_'+$map[$v]} else {'f13_app_default_isr'}
        $text += ('    BR !!{0} ; vector 0x{1:X2}, slot 0x{2:X4}' -f $symbol,$v,($start+$v*2))+"`n"
    }
    $text += @'
    BR !!f13_app_default_brk ; Reserved BRK slot 0x7E; not physically forwarded
.SECTION .text, TEXT
f13_app_default_isr:
    RETI
f13_app_default_brk:
    RETB
'@
    Generated (Join-Path $AppProject 'app_irq_table.inc') ($text+"`n")
    Generated (Join-Path $AppProject 'ftable.inc') $table
    $identity = "/* Generated from this App's app_image_config.h. Do not edit. */`n#ifndef F13_APP_IDENTITY_H`n#define F13_APP_IDENTITY_H`n"
    $identity += ('#define CAN_BOOT_APP_FIRMWARE_VERSION (0x{0:X8}UL)' -f $version)+"`n"
    $identity += ('#define CAN_BOOT_APP_FIRMWARE_BUILD ({0}UL)' -f [uint32]$image.build)+"`n"
    Generated (Join-Path $AppProject 'app_identity.h') ($identity+"#endif`n")
}
Write-Host "F13 $Mode IRQ contract $(if($CheckOnly){'verified'}else{'prepared'})."
